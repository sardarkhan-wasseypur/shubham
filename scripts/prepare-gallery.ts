import fs from "fs";
import path from "path";
import sharp from "sharp";
import { galleryItems } from "../src/content/gallery";

const TARGET_WIDTHS = [640, 1080, 1600];
const VALID_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

async function prepareGallery() {
  const rootDir = process.cwd();
  const galleryDir = path.resolve(rootDir, "public/images/gallery");
  const outputFile = path.resolve(rootDir, "src/content/gallery.generated.ts");

  if (!fs.existsSync(galleryDir)) {
    fs.mkdirSync(galleryDir, { recursive: true });
    console.log(`[gallery:prepare] Created directory: ${galleryDir}`);
  }

  const allFiles = fs.readdirSync(galleryDir);

  // Filter out generated size variants (e.g., photo-640.webp, photo-1080.avif)
  const sourceFiles = allFiles.filter((file) => {
    const ext = path.extname(file).toLowerCase();
    if (!VALID_EXTENSIONS.has(ext)) return false;
    // Check if filename matches something like name-640.webp
    const isVariant = /-(640|1080|1600)\.(webp|avif)$/i.test(file);
    return !isVariant;
  });

  console.log(`[gallery:prepare] Found ${sourceFiles.length} source images in /public/images/gallery/`);

  const generatedItems = [];

  for (const file of sourceFiles) {
    const filePath = path.join(galleryDir, file);

    // Look for matching entry in galleryItems
    const matchedEntry = galleryItems.find((item) => {
      const normalizedSrc = item.src.replace(/^\//, "");
      const expectedRel = path.posix.join("images/gallery", file);
      return (
        normalizedSrc === expectedRel ||
        item.src.endsWith(`/${file}`) ||
        item.src === file ||
        item.id === path.parse(file).name
      );
    });

    if (!matchedEntry) {
      console.warn(
        `\x1b[33m[gallery:prepare] WARNING: Image "${file}" in /public/images/gallery/ has no matching entry in gallery.ts. Image will not be shown.\x1b[0m`
      );
      continue;
    }

    try {
      const metadata = await sharp(filePath).metadata();
      const width = metadata.width || 1200;
      const height = metadata.height || 800;

      const baseName = path.parse(file).name;

      // Generate responsive sizes (640, 1080, 1600)
      for (const w of TARGET_WIDTHS) {
        const h = Math.max(1, Math.round(height * (w / width)));

        // WebP
        const webpPath = path.join(galleryDir, `${baseName}-${w}.webp`);
        await sharp(filePath)
          .resize(w, h, { withoutEnlargement: true })
          .webp({ quality: 80 })
          .toFile(webpPath);

        // AVIF
        const avifPath = path.join(galleryDir, `${baseName}-${w}.avif`);
        await sharp(filePath)
          .resize(w, h, { withoutEnlargement: true })
          .avif({ quality: 75 })
          .toFile(avifPath);
      }

      // Generate blurDataURL
      const blurW = 16;
      const blurH = Math.max(1, Math.round(16 * (height / width)));
      const blurBuffer = await sharp(filePath)
        .resize(blurW, blurH)
        .webp({ quality: 20 })
        .toBuffer();
      const blurDataURL = `data:image/webp;base64,${blurBuffer.toString("base64")}`;

      generatedItems.push({
        ...matchedEntry,
        width,
        height,
        blurDataURL,
      });

      console.log(`[gallery:prepare] Processed "${file}" (${width}x${height}) -> 6 variants generated`);
    } catch (err) {
      console.error(`[gallery:prepare] Error processing "${file}":`, err);
    }
  }

  // Write output
  const content = `// Auto-generated by "npm run gallery:prepare". Do not edit directly.
import { GalleryItem } from "./gallery";

export const generatedGalleryItems: GalleryItem[] = ${JSON.stringify(generatedItems, null, 2)};
`;

  fs.writeFileSync(outputFile, content, "utf-8");
  console.log(`[gallery:prepare] Successfully written ${generatedItems.length} items to ${outputFile}`);
}

prepareGallery().catch((err) => {
  console.error("[gallery:prepare] Fatal error:", err);
  process.exit(1);
});
